    (c_fpu_custom_mask_slit_width IS NOT NULL AND c_fpu_builtin IS NULL)
  )
);

-- Views with the synthetic ids the GMOS dynamic config mappings expect.
CREATE VIEW v_gmos_north_daytime_calibration_setup AS
  SELECT t.*,
  CASE WHEN t.c_grating_disperser          IS NOT NULL                                THEN t.c_set_id END AS c_grating_id,
  CASE WHEN t.c_fpu_custom_mask_slit_width IS NOT NULL                                THEN t.c_set_id END AS c_fpu_custom_mask_id,
  CASE WHEN t.c_fpu_custom_mask_slit_width IS NOT NULL OR t.c_fpu_builtin IS NOT NULL THEN t.c_set_id END AS c_fpu_id,
  CASE WHEN t.c_grating_wavelength         IS NOT NULL OR t.c_filter      IS NOT NULL THEN t.c_set_id END AS c_central_wavelength_id,
  COALESCE (
    t.c_grating_wavelength,
    (SELECT f.c_wavelength FROM t_gmos_north_filter f WHERE f.c_tag = t.c_filter)
  ) AS c_central_wavelength
FROM
  t_gmos_north_daytime_calibration_setup t;

CREATE VIEW v_gmos_south_daytime_calibration_setup AS
  SELECT t.*,
  CASE WHEN t.c_grating_disperser          IS NOT NULL                                THEN t.c_set_id END AS c_grating_id,
  CASE WHEN t.c_fpu_custom_mask_slit_width IS NOT NULL                                THEN t.c_set_id END AS c_fpu_custom_mask_id,
  CASE WHEN t.c_fpu_custom_mask_slit_width IS NOT NULL OR t.c_fpu_builtin IS NOT NULL THEN t.c_set_id END AS c_fpu_id,
  CASE WHEN t.c_grating_wavelength         IS NOT NULL OR t.c_filter      IS NOT NULL THEN t.c_set_id END AS c_central_wavelength_id,
  COALESCE (
    t.c_grating_wavelength,
    (SELECT f.c_wavelength FROM t_gmos_south_filter f WHERE f.c_tag = t.c_filter)
  ) AS c_central_wavelength
FROM
  t_gmos_south_daytime_calibration_setup t;

-- The mode registration covers only t_daytime_calibration; the set and setup
-- tables feed the generated sequence too, so they invalidate obscalc as well.
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    't_daytime_calibration_set',
    't_gmos_north_daytime_calibration_setup',
    't_gmos_south_daytime_calibration_setup'
  ]
  LOOP
    EXECUTE format($f$
      CREATE TRIGGER %I_invalidate_trigger
      AFTER INSERT OR UPDATE OR DELETE ON %I
      FOR EACH ROW EXECUTE FUNCTION obsid_obscalc_invalidate()
    $f$, substring(t from 3), t);
  END LOOP;
END;
$$;
