-- Calibration Sets: the ordered rows of a daytime calibration mode, each a
-- kind, an exposure count, an optional GCAL configuration and one instrument
-- setup.  The instrument-agnostic part lives here; each instrument adds a
-- setup table keyed by the set, mirroring its dynamic config columns.

CREATE TYPE e_calibration_set_type AS ENUM (
  'bias',
  'dark',
  'flat',
  'arc',
  'daytime_observe'
);

CREATE TABLE t_daytime_calibration_set (

  c_set_id         int8                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  c_observation_id d_observation_id       NOT NULL
    REFERENCES t_daytime_calibration(c_observation_id) ON DELETE CASCADE,
  c_position       int4                   NOT NULL CHECK (c_position >= 0),
  c_kind           e_calibration_set_type NOT NULL,
  c_count          int4                   NOT NULL CHECK (c_count > 0),

  -- GCAL configuration, present for flats and arcs only.
  c_gcal_continuum d_tag    REFERENCES t_gcal_continuum(c_tag) ON DELETE CASCADE,
  c_gcal_ar_arc    boolean  NOT NULL DEFAULT FALSE,
  c_gcal_cuar_arc  boolean  NOT NULL DEFAULT FALSE,
  c_gcal_thar_arc  boolean  NOT NULL DEFAULT FALSE,
  c_gcal_xe_arc    boolean  NOT NULL DEFAULT FALSE,
  c_gcal_filter    d_tag    REFERENCES t_gcal_filter(c_tag)   ON DELETE CASCADE,
  c_gcal_diffuser  d_tag    REFERENCES t_gcal_diffuser(c_tag) ON DELETE CASCADE,
  c_gcal_shutter   d_tag    REFERENCES t_gcal_shutter(c_tag)  ON DELETE CASCADE,

  UNIQUE (c_observation_id, c_position) DEFERRABLE INITIALLY DEFERRED,

  -- A flat has a continuum lamp, an arc has at least one arc lamp, and
  -- neither has both.  Every other kind has no GCAL configuration at all.
  CONSTRAINT t_daytime_calibration_set_gcal_check CHECK (
    CASE c_kind
      WHEN 'flat' THEN
        c_gcal_continuum IS NOT NULL AND
        NOT (c_gcal_ar_arc OR c_gcal_cuar_arc OR c_gcal_thar_arc OR c_gcal_xe_arc) AND
        c_gcal_filter IS NOT NULL AND c_gcal_diffuser IS NOT NULL AND c_gcal_shutter IS NOT NULL
      WHEN 'arc' THEN
        c_gcal_continuum IS NULL AND
        (c_gcal_ar_arc OR c_gcal_cuar_arc OR c_gcal_thar_arc OR c_gcal_xe_arc) AND
        c_gcal_filter IS NOT NULL AND c_gcal_diffuser IS NOT NULL AND c_gcal_shutter IS NOT NULL
      ELSE
        c_gcal_continuum IS NULL AND
        NOT (c_gcal_ar_arc OR c_gcal_cuar_arc OR c_gcal_thar_arc OR c_gcal_xe_arc) AND
        c_gcal_filter IS NULL AND c_gcal_diffuser IS NULL AND c_gcal_shutter IS NULL
    END
  )
);

CREATE INDEX ON t_daytime_calibration_set (c_observation_id);

-- Synthetic id for the nullable GCAL object in the mapping.
CREATE VIEW v_daytime_calibration_set AS
  SELECT t.*,
  CASE WHEN t.c_gcal_filter IS NOT NULL THEN t.c_set_id END AS c_gcal_id
FROM
  t_daytime_calibration_set t;

-- GMOS setups.  One row per set, the same columns as t_gmos_<site>_dynamic so
-- the dynamic config codec and mappings apply unchanged.
CREATE TABLE t_gmos_north_daytime_calibration_setup (

  c_set_id         int8             PRIMARY KEY
    REFERENCES t_daytime_calibration_set(c_set_id) ON DELETE CASCADE,
  c_observation_id d_observation_id NOT NULL,
  c_instrument     d_tag            NOT NULL DEFAULT ('GmosNorth') CHECK (c_instrument = 'GmosNorth'),

  c_exposure_time  interval         NOT NULL,

  c_xbin           d_tag            NOT NULL REFERENCES t_gmos_binning(c_tag),
  c_ybin           d_tag            NOT NULL REFERENCES t_gmos_binning(c_tag),
  c_amp_count      d_tag            NOT NULL REFERENCES t_gmos_amp_count(c_tag),
  c_amp_gain       d_tag            NOT NULL REFERENCES t_gmos_amp_gain(c_tag),
  c_amp_read_mode  d_tag            NOT NULL REFERENCES t_gmos_amp_read_mode(c_tag),

  c_dtax           d_tag            NOT NULL REFERENCES t_gmos_dtax(c_tag),
  c_roi            d_tag            NOT NULL REFERENCES t_gmos_roi(c_tag),

  c_grating_disperser  d_tag        REFERENCES t_gmos_north_disperser(c_tag),
  c_grating_order      d_tag        REFERENCES t_gmos_disperser_order(c_tag),
  c_grating_wavelength d_wavelength_pm,
  CHECK (
    (c_grating_disperser IS NULL     AND c_grating_order IS NULL     AND c_grating_wavelength IS NULL) OR
    (c_grating_disperser IS NOT NULL AND c_grating_order IS NOT NULL AND c_grating_wavelength IS NOT NULL)
  ),

  c_filter         d_tag            REFERENCES t_gmos_north_filter(c_tag),

  c_fpu_custom_mask_attachment_id d_attachment_id REFERENCES t_attachment(c_attachment_id),
  c_fpu_custom_mask_slit_width    d_tag           REFERENCES t_gmos_custom_slit_width(c_tag),
  c_fpu_builtin                   d_tag           REFERENCES t_gmos_north_fpu(c_tag),
  CHECK (
    (c_fpu_custom_mask_slit_width IS NULL     AND c_fpu_custom_mask_attachment_id IS NULL) OR
    (c_fpu_custom_mask_slit_width IS NOT NULL AND c_fpu_builtin IS NULL)
  )
);

CREATE TABLE t_gmos_south_daytime_calibration_setup (

